from pathlib import Path
import sys

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import os
os.chdir(PROJECT_ROOT)

import pandas as pd
from src.data.dataset_config import OFFICIAL_FEATURES_PATH
from src.data.loaders import read_parquet, save_parquet, append_parquet, save_csv_atomic
from src.alpha.scoring import calculate_alpha_scores
from src.utils.pipeline_io import build_lineage_metadata, validate_lineage_metadata, write_json
from src.validation.guards import assert_no_forward_columns
from src.validation.freshness_check import DerivedArtifactStale, assert_input_chain_fresh

def main():
    print("=== Running Alpha Scoring System ===")

    # 1. Load data
    stock_path = Path(OFFICIAL_FEATURES_PATH)
    bench_path = Path("data/processed/benchmark_vnindex.parquet")
    
    if not stock_path.exists():
        print(f"Error: stock_features not found at {stock_path}. Run scripts/generate_features.py first.")
        sys.exit(1)
        
    # Input-chain freshness (CLAUDE.md rule 12 / Đợt 3 NV2): existence was
    # checked above, currency was not. Catches a standalone rerun on a stale
    # feature file -- which is exactly how reports/ got regenerated by hand.
    try:
        assert_input_chain_fresh(PROJECT_ROOT, consumer="run_alpha_scoring")
    except DerivedArtifactStale as exc:
        raise SystemExit(str(exc)) from exc

    stock_df = read_parquet(str(stock_path))
    benchmark_df = read_parquet(str(bench_path)) if bench_path.exists() else pd.DataFrame()
    
    if benchmark_df.empty:
        print("[Warning] benchmark_vnindex not found. Skipping relative strength calculations.")
        
    # 2. Run Scoring
    print("Calculating alpha scores cross-sectionally...")
    scored = calculate_alpha_scores(stock_df, benchmark_df)

    # audit/PATH_TO_100.md Signal/Alpha item: belt-and-suspenders guard at the
    # artifact-write site too (same pattern as final_watchlist.py's
    # save_watchlist_outputs) -- calculate_alpha_scores already drops forward
    # columns internally, this catches anything reintroduced between the call
    # and the save (e.g. a future edit that merges another frame back in).
    scored = assert_no_forward_columns(scored, context="scripts.run_alpha_scoring", mode="drop")

    # 3. Save full history
    out_path = "data/signals/alpha_scores.parquet"
    save_parquet(scored, out_path)
    print(f"Saved full history of alpha scores to {out_path} ({len(scored)} rows)")
    
    # 4. Generate Reports
    reports_dir = Path("reports")
    reports_dir.mkdir(parents=True, exist_ok=True)
    
    # Latest date
    latest_date = scored["date"].max()
    latest_subset = scored[scored["date"] == latest_date].copy()
    
    cols = [
        "symbol", "date", "close", "alpha_score", "alpha_score_shadow_v1", "momentum_score",
        "rs_score", "trend_score", "volume_score", "volatility_score",
        "liquidity_score", "market_regime"
    ]
    available_cols = [c for c in cols if c in latest_subset.columns]

    # Report 1: daily alpha ranking
    ranking = latest_subset[available_cols].sort_values("alpha_score", ascending=False)
    save_csv_atomic(ranking, reports_dir / "daily_alpha_ranking.csv")
    print(f"Exported daily alpha ranking to {reports_dir / 'daily_alpha_ranking.csv'} ({len(ranking)} symbols)")

    # Report 2: top 20 watchlist.
    #
    # The comment here used to read "(alpha_score >= 75 or top 20)". The code
    # never applied that bar -- it is a plain head(20), so the file always has
    # exactly 20 rows no matter how weak the scores are (AUDIT_NOTEBOOKS_REPORT.md
    # Đợt 5 (A)). Rather than silently start filtering on a number that was never
    # pre-registered, keep the selection unchanged and state the composition:
    # how many of the 20 clear the 75 the comment always claimed.
    STRONG_ALPHA_REFERENCE = 75.0
    top_watchlist = ranking.head(20).copy()
    _alpha = pd.to_numeric(top_watchlist.get("alpha_score", pd.Series(dtype=float)), errors="coerce").fillna(0.0)
    n_strong = int(_alpha.ge(STRONG_ALPHA_REFERENCE).sum())
    top_watchlist["evidence_basis"] = [
        f"alpha_score >= {STRONG_ALPHA_REFERENCE:g}" if v else f"top-20 rank only (alpha_score < {STRONG_ALPHA_REFERENCE:g})"
        for v in _alpha.ge(STRONG_ALPHA_REFERENCE)
    ]
    evidence_headline = (
        f"top_watchlist: {len(top_watchlist)} mã, trong đó {n_strong} có "
        f"alpha_score >= {STRONG_ALPHA_REFERENCE:g} và {len(top_watchlist) - n_strong} "
        f"chỉ có mặt nhờ thứ hạng top-20. Danh sách luôn dài đúng 20 dòng bất kể "
        f"điểm mạnh hay yếu."
    )
    save_csv_atomic(top_watchlist, reports_dir / "top_watchlist.csv")
    print(f"Exported top 20 watchlist to {reports_dir / 'top_watchlist.csv'}")
    print(f"  {evidence_headline}")

    # Lineage (audit gate #12): daily_alpha_ranking.csv/top_watchlist.csv are
    # plain CSVs with no metadata slot of their own -- write a sidecar so both
    # can be traced back to the exact features snapshot + code version that
    # produced them, same convention as portfolio_risk_report.json.
    lineage = validate_lineage_metadata(
        build_lineage_metadata(OFFICIAL_FEATURES_PATH, base_dir=PROJECT_ROOT),
        label="alpha_scoring_metadata.json",
    )
    write_json(
        {
            "latest_date": latest_date.date().isoformat(),
            "symbol_count": int(len(ranking)),
            "top_watchlist_count": int(len(top_watchlist)),
            # Đợt 5 (A): a bare count of 20 tells a reader nothing about strength.
            "evidence_summary": {
                "tier": "top_watchlist",
                "count": int(len(top_watchlist)),
                "ranked_by": "alpha_score",
                "score_threshold_applied": False,
                "reference_threshold": STRONG_ALPHA_REFERENCE,
                "n_meeting_reference": n_strong,
                "n_rank_only": int(len(top_watchlist)) - n_strong,
                "alpha_score_min": round(float(_alpha.min()), 2) if len(_alpha) else None,
                "alpha_score_max": round(float(_alpha.max()), 2) if len(_alpha) else None,
                "headline": evidence_headline,
            },
            "generated_files": [
                "data/signals/alpha_scores.parquet",
                "reports/daily_alpha_ranking.csv",
                "reports/top_watchlist.csv",
            ],
            "lineage": lineage,
        },
        reports_dir / "alpha_scoring_metadata.json",
    )
    print(f"Wrote lineage metadata to {reports_dir / 'alpha_scoring_metadata.json'}")

    # Shadow log: v2 (deployed) vs v1 (shadow) side by side, appended daily
    # so the live out-of-sample comparison accumulates day by day starting
    # from today (docs/reports/scoring/SCORE_V2_REPORT.md).
    if "alpha_score_shadow_v1" in latest_subset.columns:
        shadow_cols = ["symbol", "date", "alpha_score", "alpha_score_shadow_v1"]
        shadow_today = latest_subset[shadow_cols].copy()
        append_parquet(shadow_today, "data/signals/alpha_score_shadow_log.parquet", subset=["symbol", "date"])
        print(f"Appended {len(shadow_today)} rows to data/signals/alpha_score_shadow_log.parquet "
              f"(v2 vs v1 shadow comparison, date={latest_date.date()})")

    print("=== Alpha Scoring Complete ===")

if __name__ == "__main__":
    main()
