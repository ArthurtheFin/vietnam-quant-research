"""Single source of truth for the OFFICIAL dataset paths this project's
production pipeline must read from (audit critical finding P0-2 / gate #6).

`data/processed/stock_features.parquet` (and its siblings
`clean_daily_ohlcv.parquet` / `market_features.parquet`) must ALWAYS be
produced by `scripts/generate_features.py` reading `OFFICIAL_PRICE_RAW_DIR`
below. If any of these three files on disk was not (re)generated by that
script after `OFFICIAL_PRICE_RAW_DIR` was last updated, it is stale and
must be regenerated before use -- see `docs/reports/data/DATA_BASELINE.md` and
`data/quarantine_existing_v1/README.md` for the incident this guards
against (a ~29-day raw/adjusted-close mixing bug that silently corrupted
a large, uncatalogued fraction of the universe; confirmed independently
in this round via an exact 2x close-price mismatch on VIC/TCB/VCB/MBB/
HDB/BID/VNM/MWG/HPG between the stale file and `full_history_v2`).

Import these constants everywhere a script/module needs one of these
paths -- do not hardcode the path string directly. This is the one place
to change if the official path ever moves.
"""
from __future__ import annotations

# The one verified, bug-fixed raw OHLCV source (docs/reports/data/DATA_BASELINE.md). Every
# feature/signal/portfolio pipeline must trace back to this, either
# directly or via OFFICIAL_FEATURES_PATH regenerated from it.
OFFICIAL_PRICE_RAW_DIR = "data/full_history_v2/raw"

# Canonical derived-data paths. Must always be the *output* of
# scripts/generate_features.py reading OFFICIAL_PRICE_RAW_DIR above --
# never read, patched, or independently regenerated from any other source.
OFFICIAL_CLEAN_OHLCV_PATH = "data/processed/clean_daily_ohlcv.parquet"
OFFICIAL_FEATURES_PATH = "data/processed/stock_features.parquet"
OFFICIAL_MARKET_FEATURES_PATH = "data/processed/market_features.parquet"

# Forbidden: anything under here is known-contaminated (the raw/adjusted-
# close mixing bug, docs/reports/data/DATA_BASELINE.md) or otherwise superseded. No
# production code path (src/, scripts/) may read from here.
QUARANTINE_DIR = "data/quarantine_existing_v1"

# Superseded pre-backfill raw source. New code should not read from this
# directory; it is retained only because src/data/fetch_daily.py's writer
# functions still default to it for backward compatibility with any
# external caller that hasn't been updated to target OFFICIAL_PRICE_RAW_DIR.
# See PUSH_REVIEW.md's 2026-07-13 note on why data/processed/ went stale:
# a background job kept refreshing this directory via
# scripts/update_daily_data.py, independently of full_history_v2.
LEGACY_PRICE_RAW_DIR = "data/raw/daily_ohlcv"

# Directories owned end-to-end by the automated nightly pipeline
# (scripts/daily_run.sh -> scripts/run_daily_pipeline.py). Everything inside
# them is either produced or consumed by a pipeline step, so nothing outside
# that pipeline may write there -- enforced in src/data/production_guard.py.
#
# Added after AUDIT_NOTEBOOKS_REPORT.md OPEN_AUTO #2/#3 found notebook 12
# overwriting data/signals/alpha_scores.parquet and reports/top_watchlist.csv
# by hand, two hours after the pipeline had produced them, leaving
# reports/alpha_scoring_metadata.json's lineage claim describing a file that on
# disk had a different schema.
PIPELINE_OWNED_DIRS = (
    "data/processed",
    "data/signals",
    "data/output",
    "reports",
)

# Where notebooks should write instead. Deliberately NOT pipeline-owned --
# nothing in the automated pipeline reads from here.
NOTEBOOK_OUTPUT_DIR = "notebooks/outputs"
